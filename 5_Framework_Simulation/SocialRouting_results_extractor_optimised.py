#!/usr/bin/env python3
"""
Social Routing – Results Extractor

Scans all simulation runs organised as:
  Output/Simulations/scheme_*/case_*_rep_*

Extracts:
- macro-level results per cycle
- per-user additional travel time (when UC baseline is available)

Cycle alignment (compatible with the unchanged simulation framework and v5 graphs):
- cycle-c travel times / network benefit are generated by select_social_store[c-1];
- select_social_store[c] is the POST-cycle-c participation state;
- `group` and histogram `group` now mean participation DURING the cycle;
- `group_start` and `group_end` are both retained in per-user output;
- legacy macro `participation_rate` and `lost_users` remain END-of-cycle
  values because generate_graphs_from_extractor_optimised_v5.py already shifts
  those to the corresponding start-of-cycle when plotting.

Outputs:
  extracted_output/macro_all_sim<hours>.csv
  extracted_output/peruser_all_sim<hours>.csv
  Optional ZIP bundles the legacy outputs plus route-day extensions when present.
  route_day_cycle_by_rep_sim<hours>.csv and replication means for all cases.
  Per-user route-day outputs are stored compressed per-run (optional aggregate).
"""

