def extract_route_day_outputs(results_folder: str, sim_hours: int,
                              *, mode: str = 'auto', include_users: bool = False,
                              save_folder: str = None, expected_cycles: int = 20):
    """Aggregate output-only cycle summaries without altering legacy CSVs.

    mode=auto: skip for older runs with no route-day output, require all runs
               to have the new output if at least one run has it.
    mode=required: require output for all run folders.
    mode=off: disable this feature (e.g. analysing historical results).

    Per-user observations remain in each run's compressed CSV by default.
    Pass --route-day-include-users to also build a combined compressed file.
    """
    if mode == 'off':
        return []
    if expected_cycles < 1:
        raise ValueError('route-day expected cycles must be >= 1')
    run_dirs = find_all_run_dirs(results_folder)
    if not run_dirs:
        if mode == 'required':
            raise FileNotFoundError('No run directories found for route-day extraction')
        return []

    supported = [d for d in run_dirs if (d / 'route_day_outputs').is_dir()]
    if not supported:
        if mode == 'required':
            raise FileNotFoundError('No route_day_outputs found; rerun using the extended framework')
        print('[INFO] No route-day outputs present (legacy run). Skipping route-day extraction.')
        return []
    if len(supported) != len(run_dirs):
        missing = sorted(set(run_dirs).difference(supported))
        raise FileNotFoundError(
            f'Found route-day outputs in {len(supported)}/{len(run_dirs)} runs; '
            f'cannot aggregate incomplete experiment. Missing: {missing[:5]}'
        )

    out_dir = Path(save_folder) if save_folder else Path(results_folder) / 'extracted_output'
    out_dir.mkdir(parents=True, exist_ok=True)
    by_rep_path = out_dir / f'route_day_cycle_by_rep_sim{sim_hours}.csv'
    group_path = out_dir / f'route_day_cycle_mean_across_reps_sim{sim_hours}.csv'
    late_path = out_dir / f'route_day_last_cycles_by_case_sim{sim_hours}.csv'
    users_path = out_dir / f'route_day_users_sim{sim_hours}.csv.gz'

    all_summaries = []
    user_paths = []
    detail_cycles = set()
    for run_dir in run_dirs:
        with open(run_dir / 'config.json', encoding='utf-8') as f:
            cfg = json.load(f)
        scheme = cfg['scheme']
        case_id = cfg['case_id']
        case_label = cfg['case_label']
        rep_id = cfg['rep_id']
        folder = run_dir / 'route_day_outputs'
        files = sorted(folder.glob('cycle_*_summary.csv'))
        if not files:
            raise FileNotFoundError(f'No route-day cycle summaries in {folder}')
        cycles = [int(p.stem.split('_')[1]) for p in files]
        if cycles != list(range(1, max(cycles) + 1)):
            raise ValueError(f'Missing route-day summary cycle(s) in {folder}: {cycles}')
        # Require the complete requested simulation horizon. The main legacy
        # extractor already loads the framework pickle, so do not load it a
        # second time just for the extra sidecar output.
        expected = expected_cycles
        if cycles != list(range(1, expected + 1)):
            raise ValueError(f'Run {run_dir}: expected {expected} route-day cycles, found {cycles}')
        expected_users = None
        previous_end_share = None

        for cycle, path in zip(cycles, files):
            rows = pd.read_csv(path)
            if len(rows) != 2 or set(rows['group_start']) != {'participant', 'nonparticipant'}:
                raise ValueError(f'Invalid group rows in {path}')
            if (rows['scheme'] != scheme).any() or (rows['case_id'] != case_id).any() \
                or (rows['case_label'] != case_label).any() \
                or (rows['rep_id'] != rep_id).any() or (rows['cycle'] != cycle).any():
                raise ValueError(f'Unexpected run/cycle metadata in {path}')
            if rows.loc[rows['group_start'] == 'nonparticipant', 'n_valid_srday_users'].sum() != 0:
                raise ValueError(f'Non-participant SR days found in {path}')
            n_this_cycle = int(rows['n_users'].sum())
            if expected_users is None:
                expected_users = n_this_cycle
            if n_this_cycle != expected_users:
                raise ValueError(f'User count changed in {path}')
            p_start = float(rows['participation_rate_start'].iloc[0])
            p_end = float(rows['participation_rate_end'].iloc[0])
            n_part = int(rows.loc[rows['group_start'] == 'participant', 'n_users'].iloc[0])
            if not np.isclose(p_start, n_part / expected_users, rtol=0, atol=1e-10):
                raise ValueError(f'Participation start mismatch in {path}')
            if previous_end_share is not None and not np.isclose(
                previous_end_share, p_start, rtol=0, atol=1e-10
            ):
                raise ValueError(f'Participation states not continuous between cycles in {path}')
            previous_end_share = p_end
            all_summaries.append(rows)

        if include_users:
            paths = sorted(folder.glob('cycle_*_users.csv.gz'))
            if not paths:
                raise FileNotFoundError(f'No per-user route-day files in {folder}')
            user_cycles = {int(p.name.split('_')[1]) for p in paths}
            if max(user_cycles) != expected or user_cycles != set(range(min(user_cycles), expected + 1)):
                raise ValueError(f'Incomplete per-user route-day files in {folder}')
            detail_cycles.add(min(user_cycles))
            user_paths.extend(paths)
        print(f'[Route days] Read {scheme} / {case_label} / rep {rep_id}: {len(cycles)} cycles', flush=True)

    if include_users and len(detail_cycles) != 1:
        raise ValueError(f'Different user-detail starting cycles across runs: {detail_cycles}')
    combined = pd.concat(all_summaries, ignore_index=True).sort_values(
        ['scheme', 'case_id', 'rep_id', 'cycle', 'group_start']
    )
    combined.to_csv(by_rep_path, index=False)
    id_cols = ['scheme', 'case_id', 'case_label', 'cycle', 'group_start']
    excluded = set(id_cols) | {'rep_id'}
    metrics = [c for c in combined.select_dtypes(include='number').columns if c not in excluded]
    across_reps = combined.groupby(id_cols, as_index=False)[metrics].mean()
    across_reps.to_csv(group_path, index=False)

    # Latest five cycles of EACH run, rather than assuming exactly 20 cycles.
    final_records = []
    for (_, _, _, rep, group), part in combined.groupby(
            ['scheme', 'case_id', 'case_label', 'rep_id', 'group_start'], sort=False):
        final_records.append(part.loc[part['cycle'] >= part['cycle'].max() - 4])
    late = pd.concat(final_records, ignore_index=True)
    late_means = late.groupby(['scheme','case_id','case_label','group_start'], as_index=False)[metrics].mean()
    late_means.to_csv(late_path, index=False)
    outputs = [by_rep_path, group_path, late_path]

    if include_users:
        first_header = None
        with gzip.open(users_path, 'wt', newline='') as dest:
            for path in user_paths:
                with gzip.open(path, 'rt', newline='') as source:
                    header = source.readline()
                    if first_header is None:
                        first_header = header
                        dest.write(header)
                    elif header != first_header:
                        raise ValueError(f'Route-day per-user schema mismatch: {path}')
                    shutil.copyfileobj(source, dest, length=1024 * 1024)
        outputs.append(users_path)
    print(f'[OK] Route-day results for {len(run_dirs)} runs: {out_dir}', flush=True)
    return outputs

